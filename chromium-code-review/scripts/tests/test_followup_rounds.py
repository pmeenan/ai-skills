    def test_reviewer_identity_domain_equivalence_override_and_warning(self) -> None:
        _, review, parent_sha, sha_ps1, sha_ps2, sha_ps3 = self.make_repo_and_review()
        write(
            review / "detail.json",
            json.dumps(
                {
                    "owner": {"email": "author@chromium.org"},
                    "revisions": {
                        sha_ps1: {"_number": 1},
                        sha_ps2: {"_number": 2},
                        sha_ps3: {"_number": 3, "commit": {"message": "Docs update\n"}},
                    },
                    "messages": [],
                }
            ),
        )
        write(
            review / "comments.json",
            json.dumps(
                {
                    "docs/readme.md": [
                        {
                            "id": "c_alice_ps1",
                            "patch_set": 1,
                            "line": 2,
                            "updated": "2026-07-01 10:00:00.000000000",
                            "unresolved": False,
                            "author": {"email": "alice@chromium.org"},
                            "message": "Nit on line 2.",
                        }
                    ]
                }
            ),
        )

        # 1. `alice@google.com` in `pin.md` matches `alice@chromium.org` in `comments.json`.
        write(
            review / "pin.md",
            "# CL 9999999 — patchset 3 pin\n\n"
            "- Pinned patchset: 3\n"
            f"- Revision SHA: {sha_ps3}\n"
            f"- Parent SHA: {parent_sha}\n"
            f"- Worktree: {review.parent / 'repo'} (rev-parse verified)\n"
            "- Reviewer email: alice@google.com\n",
        )
        run("python3", str(PROFILE), str(review))
        prof_equiv = json.loads((review / "profile.json").read_text(encoding="utf-8"))
        hist_equiv = prof_equiv["prior_context"]["reviewer_history"]
        self.assertTrue(hist_equiv["same_reviewer_followup"])
        self.assertEqual(2, hist_equiv["review_round"])
        self.assertEqual(["alice@chromium.org"], hist_equiv["matched_reviewer_emails"])
        self.assertIsNone(hist_equiv["identity_warning"])

        # 2. A non-equivalent domain (`alice@external.org`) does NOT match
        # `alice@chromium.org` and emits a visible warning in `profile.md`.
        write(
            review / "pin.md",
            "# CL 9999999 — patchset 3 pin\n\n"
            "- Pinned patchset: 3\n"
            f"- Revision SHA: {sha_ps3}\n"
            f"- Parent SHA: {parent_sha}\n"
            f"- Worktree: {review.parent / 'repo'} (rev-parse verified)\n"
            "- Reviewer email: alice@external.org\n",
        )
        run("python3", str(PROFILE), str(review))
        prof_unmatched = json.loads((review / "profile.json").read_text(encoding="utf-8"))
        hist_unmatched = prof_unmatched["prior_context"]["reviewer_history"]
        self.assertFalse(hist_unmatched["same_reviewer_followup"])
        self.assertEqual(1, hist_unmatched["review_round"])
        self.assertEqual(["alice@chromium.org"], hist_unmatched["unmatched_prior_comment_authors"])
        self.assertIsNotNone(hist_unmatched["identity_warning"])
        self.assertIn(
            "- **Reviewer identity warning:**",
            (review / "profile.md").read_text(encoding="utf-8"),
        )

        # 3. `- Reviewer email:` in `directives.md` overrides `pin.md` and accepts aliases.
        write(
            review / "directives.md",
            "- Mode: follow-up review\n- Reviewer email: alice@external.org, alice@google.com\n",
        )
        run("python3", str(PROFILE), str(review))
        prof_override = json.loads((review / "profile.json").read_text(encoding="utf-8"))
        hist_override = prof_override["prior_context"]["reviewer_history"]
        self.assertEqual("directives.md", hist_override["reviewer_email_source"])
        self.assertTrue(hist_override["same_reviewer_followup"])
        self.assertEqual(2, hist_override["review_round"])
        self.assertIsNone(hist_override["identity_warning"])


